-- 1. TABLA REGION

CREATE TABLE region (
    id_region NUMBER(2),
    nombre VARCHAR2(50) NOT NULL,
    CONSTRAINT region_pk PRIMARY KEY (id_region)
);

-- 2. TABLA NACIONALIDAD

CREATE TABLE nacionalidad (
    id_nacion NUMBER(3)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 210 INCREMENT BY 2),
    descripcion VARCHAR2(50) NOT NULL,
    CONSTRAINT nacionalidad_pk PRIMARY KEY (id_nacion)
);

-- 3. TABLA ESCUELA_FUTBOL

CREATE TABLE escuela_futbol (
    id_escuela NUMBER(4),
    nombre VARCHAR2(50) NOT NULL,
    capacidad NUMBER(4) NOT NULL,
    fecha_fundacion DATE NOT NULL,
    CONSTRAINT escuela_futbol_pk PRIMARY KEY (id_escuela)
);

-- 4. TABLA ASOCIACION

CREATE TABLE asociacion (
    cod_asociacion NUMBER(2),
    nombre VARCHAR2(50) NOT NULL,
    fecha_creacion DATE NOT NULL,
    tipo VARCHAR2(20) NOT NULL,
    CONSTRAINT asociacion_pk PRIMARY KEY (cod_asociacion),
    
    CONSTRAINT asociacion_fecha_ck
    CHECK (fecha_creacion >= DATE '1980-12-31')
);

-- 5. TABLA CLUB_FUTBOL

CREATE TABLE club_futbol (
    codigo_club NUMBER(3),
    nombre_club VARCHAR2(50) NOT NULL,
    patrimonio NUMBER(12) NOT NULL,
    direccion VARCHAR2(50) NOT NULL,
    tipo_club VARCHAR2(20) NOT NULL,
    CONSTRAINT club_futbol_pk PRIMARY KEY (codigo_club),
    
    CONSTRAINT club_futbol_nombre_uk
        UNIQUE (nombre_club)
);

-- Secuencia para generar el codigo de CLUB_FUTBOL
-- Inicia en 703 y aumenta de 4 en 4

CREATE SEQUENCE seq_club_futbol
START WITH 703
INCREMENT BY 4;


-- 6. TABLA IDIOMA

CREATE TABLE idioma (
    id_idioma NUMBER(3),
    nombre_idioma VARCHAR2(30) NOT NULL,
    CONSTRAINT idioma_pk PRIMARY KEY (id_idioma)
);

-- 7. TABLA COMUNA

CREATE TABLE comuna (
    id_comuna NUMBER(3),
    nombre VARCHAR2(50) NOT NULL,
    region_id_region NUMBER(2) NOT NULL,
    CONSTRAINT comuna_pk PRIMARY KEY (id_comuna),
    CONSTRAINT comuna_region_fk
        FOREIGN KEY (region_id_region)
        REFERENCES region(id_region)
);

-- 8. TABLA TRABAJADOR

CREATE TABLE trabajador (
    cod_inscripcion NUMBER(9),
    rut NUMBER(8) NOT NULL,
    dv CHAR(1) NOT NULL,
    nombres VARCHAR2(50) NOT NULL,
    apellidos VARCHAR2(50) NOT NULL,
    sueldo_base NUMBER(10) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    genero VARCHAR2(20) NOT NULL,
    estado_civil VARCHAR2(20) NOT NULL,
    telefono_movil VARCHAR2(20) NOT NULL,
    direccion VARCHAR2(50) NOT NULL,
    email VARCHAR2(50),
    comuna_id_comuna NUMBER(3) NOT NULL,
    nacionalidad_id_nacion NUMBER(3) NOT NULL,

    CONSTRAINT trabajador_pk
        PRIMARY KEY (cod_inscripcion),

    CONSTRAINT trabajador_comuna_fk
        FOREIGN KEY (comuna_id_comuna)
        REFERENCES comuna(id_comuna),

    CONSTRAINT trabajador_nacionalidad_fk
        FOREIGN KEY (nacionalidad_id_nacion)
        REFERENCES nacionalidad(id_nacion)
);

-- 9. TABLA PERSONAL_PLANTA

CREATE TABLE personal_planta (
    cod_inscripcion NUMBER(9),
    cantidad_horas_trabajadas NUMBER(3),
    valor_horas_extras NUMBER(8),
    club_futbol_codigo_club NUMBER(3) NOT NULL,

    CONSTRAINT personal_planta_pk
        PRIMARY KEY (cod_inscripcion),

    CONSTRAINT personal_planta_trabajador_fk
        FOREIGN KEY (cod_inscripcion)
        REFERENCES trabajador(cod_inscripcion),

    CONSTRAINT personal_planta_club_futbol_fk
        FOREIGN KEY (club_futbol_codigo_club)
        REFERENCES club_futbol(codigo_club)
);

-- 10. TABLA JUGADOR

CREATE TABLE jugador (
    cod_inscripcion NUMBER(9),
    puesto VARCHAR2(30) NOT NULL,
    monto_total_premios NUMBER(10) NOT NULL,
    anio_dejo_amateurism NUMBER(4),
    asociacion_cod_asociacion NUMBER(2) NOT NULL,
    escuela_futbol_id_escuela NUMBER(4),

    CONSTRAINT jugador_pk
        PRIMARY KEY (cod_inscripcion),

    CONSTRAINT jugador_trabajador_fk
        FOREIGN KEY (cod_inscripcion)
        REFERENCES trabajador(cod_inscripcion),

    CONSTRAINT jugador_asociacion_fk
        FOREIGN KEY (asociacion_cod_asociacion)
        REFERENCES asociacion(cod_asociacion),

    CONSTRAINT jugador_escuela_futbol_fk
        FOREIGN KEY (escuela_futbol_id_escuela)
        REFERENCES escuela_futbol(id_escuela)
);

-- 11. TABLA PERMANENCIA_CLUB

CREATE TABLE permanencia_club (
    fecha_incorporacion DATE,
    fecha_fin_contrato DATE,
    jugador_cod_inscripcion NUMBER(9),
    club_futbol_codigo_club NUMBER(3),

    CONSTRAINT permanencia_club_pk
        PRIMARY KEY (
            jugador_cod_inscripcion,
            club_futbol_codigo_club,
            fecha_incorporacion
        ),

    CONSTRAINT permanencia_club_jugador_fk
        FOREIGN KEY (jugador_cod_inscripcion)
        REFERENCES jugador(cod_inscripcion),

    CONSTRAINT permanencia_club_club_futbol_fk
        FOREIGN KEY (club_futbol_codigo_club)
        REFERENCES club_futbol(codigo_club)
);

-- 12. TABLA DOMINIO_IDIOMA

CREATE TABLE dominio_idioma (
    nivel_dominio VARCHAR2(25) NOT NULL,
    jugador_cod_inscripcion NUMBER(9),
    idioma_id_idioma NUMBER(3),

    CONSTRAINT dominio_idioma_pk
        PRIMARY KEY (
            jugador_cod_inscripcion,
            idioma_id_idioma
        ),

    CONSTRAINT dominio_idioma_jugador_fk
        FOREIGN KEY (jugador_cod_inscripcion)
        REFERENCES jugador(cod_inscripcion),

    CONSTRAINT dominio_idioma_idioma_fk
        FOREIGN KEY (idioma_id_idioma)
        REFERENCES idioma(id_idioma)
);

